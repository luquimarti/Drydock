// Headless Ymir runner: boots a disc with a BIOS, runs N frames, presses
// pad buttons on scripted frames, writes PNG snapshots and reports speed.
//   ymir-headless <bios> <cue> <frames> [--press F:F2:BTN ...] [--png F ...] [--dump FRAME:PREFIX ...]
//                 [--nothreads] [--cache] [--trace out.txt] [--native | --library game.so]
#include <ymir/ymir.hpp>
#include <ymir_recomp/runtime.hpp>
#include <stb_image_write.h>

#include <chrono>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <memory>
#include <set>
#include <string>
#include <vector>

using namespace ymir;

struct Press { uint64_t from, to; uint16_t mask; };
static std::vector<Press> g_press;
static uint64_t g_frame = 0;
static std::set<uint64_t> g_png;
static uint64_t g_frames_done = 0;
static uint64_t g_audio = 0;

static uint16_t btn(const std::string &s) {
    using B = peripheral::Button;
    if (s == "start") return (uint16_t)B::Start;
    if (s == "a") return (uint16_t)B::A;
    if (s == "b") return (uint16_t)B::B;
    if (s == "c") return (uint16_t)B::C;
    if (s == "up") return (uint16_t)B::Up;
    if (s == "down") return (uint16_t)B::Down;
    if (s == "left") return (uint16_t)B::Left;
    if (s == "right") return (uint16_t)B::Right;
    return 0;
}

static void OnPad(peripheral::PeripheralReport &rep, void *) {
    uint16_t pressed = 0;
    for (auto &p : g_press)
        if (g_frame >= p.from && g_frame < p.to) pressed |= p.mask;
    rep.report.controlPad.buttons = (peripheral::Button)(0xFFFFu & ~pressed);
}

static void OnFrame(uint32 *fb, uint32 w, uint32 h, void *) {
    g_frames_done++;
    if (g_png.count(g_frame)) {
        std::vector<uint8_t> rgb((size_t)w * h * 3);
        for (size_t i = 0; i < (size_t)w * h; i++) {
            uint32 c = fb[i];
            rgb[i * 3 + 0] = (uint8_t)(c);
            rgb[i * 3 + 1] = (uint8_t)(c >> 8);
            rgb[i * 3 + 2] = (uint8_t)(c >> 16);
        }
        char name[64];
        snprintf(name, sizeof name, "frame_%06llu.png", (unsigned long long)g_frame);
        stbi_write_png(name, (int)w, (int)h, 3, rgb.data(), (int)w * 3);
        fprintf(stderr, "[png] %s %ux%u\n", name, w, h);
    }
}

static void OnSample(sint16, sint16, void *) { g_audio++; }

#ifdef YMIR_RECOMP_HAVE_NATIVE
// Generated by sh2recomp for the game being run (linked in).
extern "C" void drydock_register(drydock::Registrar *rt);
#endif

static std::vector<std::pair<uint64_t, std::string>> g_dumps;

int main(int argc, char **argv) {
    if (argc < 4) { fprintf(stderr, "usage: %s bios cue frames [opts]\n", argv[0]); return 2; }
    uint64_t frames = strtoull(argv[3], nullptr, 0);
    bool threads = true, cache = false, native = false;
    const char *tracePath = nullptr;
    const char *libraryPath = nullptr; // game built as a shared library (sh2recomp + drydock build)
    for (int i = 4; i < argc; i++) {
        std::string a = argv[i];
        if (a == "--press" && i + 1 < argc) {
            // from:to:button
            std::string v = argv[++i];
            auto c1 = v.find(':'), c2 = v.find(':', c1 + 1);
            g_press.push_back({strtoull(v.substr(0, c1).c_str(), nullptr, 0),
                               strtoull(v.substr(c1 + 1, c2 - c1 - 1).c_str(), nullptr, 0),
                               btn(v.substr(c2 + 1))});
        } else if (a == "--png" && i + 1 < argc) g_png.insert(strtoull(argv[++i], nullptr, 0));
        else if (a == "--nothreads") threads = false;
        else if (a == "--cache") cache = true;
        else if (a == "--trace" && i + 1 < argc) tracePath = argv[++i];
        else if (a == "--native") native = true;
        else if (a == "--library" && i + 1 < argc) libraryPath = argv[++i];
        else if (a == "--dump" && i + 1 < argc) {
            // frame:prefix -> writes prefix-hwram.bin and prefix-lwram.bin after that frame
            std::string v = argv[++i];
            auto c = v.find(':');
            g_dumps.push_back({strtoull(v.substr(0, c).c_str(), nullptr, 0), v.substr(c + 1)});
        }
    }

    auto sat = std::make_unique<Saturn>();
    {
        std::ifstream f(argv[1], std::ios::binary);
        std::vector<uint8> ipl(sys::kIPLSize);
        f.read((char *)ipl.data(), ipl.size());
        if ((size_t)f.gcount() != sys::kIPLSize) { fprintf(stderr, "bad BIOS\n"); return 1; }
        sat->LoadIPL(std::span<uint8, sys::kIPLSize>(ipl.data(), sys::kIPLSize));
    }
    media::Disc disc;
    if (!media::LoadDisc(argv[2], disc, true, [](media::MessageType, std::string m) {
            fprintf(stderr, "[loader] %s\n", m.c_str()); })) {
        fprintf(stderr, "disc load failed\n"); return 1;
    }
    sat->configuration.swRenderer.threadedVDP1 = threads;
    sat->configuration.swRenderer.threadedVDP2 = threads;
    sat->configuration.swRenderer.threadedDeinterlacer = threads;
    sat->EnableSH2CacheEmulation(cache);
    sat->LoadDisc(std::move(disc));
    sat->AutodetectRegion();

    auto &port = sat->SMPC.GetPeripheralPort1();
    port.SetPeripheralReportCallback({OnPad});
    port.ConnectControlPad();
    sat->VDP.SetSoftwareRenderCallback({OnFrame});
    sat->SCSP.SetSampleCallback({OnSample});
    {
        // Console settings as already configured on the user's machine
        // (language/clock set), so the BIOS skips its first-boot setup.
        smpc::PersistentSMPCData d{};
        d.SMEM = {0x53, 0x00, 0x00, 0x00};
        d.STE = true;
        sat->SMPC.LoadPersistentData(d);
    }
    {
        std::error_code ec;
        sat->LoadInternalBackupMemoryImage("bup-int.bin", false, ec);
        if (ec) fprintf(stderr, "[bup] %s\n", ec.message().c_str());
    }
    sat->Reset(true);

    ymir_recomp::Runtime rt(*sat);
    if (tracePath) {
        rt.StartTrace();
        fprintf(stderr, "[recomp] tracing control transfers\n");
    } else if (libraryPath) {
        std::string err;
        if (!rt.LoadGameLibrary(libraryPath, err)) {
            fprintf(stderr, "[recomp] %s\n", err.c_str());
            return 1;
        }
        rt.Attach();
        native = true;
        fprintf(stderr, "[recomp] native code from %s: %zu entry points\n", libraryPath, rt.EntryCount());
    } else if (native) {
#ifdef YMIR_RECOMP_HAVE_NATIVE
        rt.RegisterStatic(drydock_register);
        rt.Attach();
        fprintf(stderr, "[recomp] native code: %zu entry points\n", rt.EntryCount());
#else
        fprintf(stderr, "[recomp] this build has no generated code (configure with -DRECOMP_GENERATED=...)\n");
        return 1;
#endif
    }

    auto t0 = std::chrono::steady_clock::now();
    auto tlast = t0;
    uint64_t lastNative = 0, lastInterp = 0;
    for (g_frame = 0; g_frame < frames; g_frame++) {
        sat->RunFrame();
        for (const auto &[df, prefix] : g_dumps) {
            if (df != g_frame) continue;
            if (FILE *f = fopen((prefix + "-hwram.bin").c_str(), "wb")) {
                fwrite(sat->mem.WRAMHigh.data(), 1, sat->mem.WRAMHigh.size(), f);
                fclose(f);
            }
            if (FILE *f = fopen((prefix + "-lwram.bin").c_str(), "wb")) {
                fwrite(sat->mem.WRAMLow.data(), 1, sat->mem.WRAMLow.size(), f);
                fclose(f);
            }
        }
        if ((g_frame + 1) % 600 == 0) {
            auto t = std::chrono::steady_clock::now();
            double dt = std::chrono::duration<double>(t - tlast).count();
            const auto &st = rt.GetStats();
            const double nc = (double)(st.nativeCycles - lastNative);
            const double ii = (double)(st.interpretedInstructions - lastInterp);
            char share[64] = "";
            if (native && nc + ii > 0) snprintf(share, sizeof share, ", SH-2 %.1f%% native", 100.0 * nc / (nc + ii));
            lastNative = st.nativeCycles;
            lastInterp = st.interpretedInstructions;
            fprintf(stderr, "[speed] frames %llu-%llu: %.1f fps (%.0f%% of 60)%s\n",
                    (unsigned long long)(g_frame - 599), (unsigned long long)g_frame,
                    600 / dt, 600 / dt / 60.0 * 100, share);
            tlast = t;
        }
    }
    double total = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    fprintf(stderr, "[done] %llu frames in %.1f s = %.1f fps avg, %llu rendered, %llu audio samples, MSH2 PC=%08X\n",
            (unsigned long long)frames, total, frames / total, (unsigned long long)g_frames_done,
            (unsigned long long)g_audio, sat->masterSH2.GetProbe().PC());
    if (tracePath) {
        FILE *f = fopen(tracePath, "w");
        if (f) {
            rt.WriteTrace(f);
            fclose(f);
            fprintf(stderr, "[recomp] trace written to %s\n", tracePath);
        }
    }
    if (native) {
        const auto &st = rt.GetStats();
        fprintf(stderr, "[recomp] native entries %llu, yielded at entry %llu, signature mismatches %llu\n",
                (unsigned long long)st.nativeEntries, (unsigned long long)st.noProgress,
                (unsigned long long)st.signatureMismatch);
        const double tot = (double)st.nativeCycles + (double)st.interpretedInstructions;
        fprintf(stderr, "[recomp] SH-2 work: %.1f%% native (%llu native cycles, %llu interpreted instructions)\n",
                tot > 0 ? 100.0 * st.nativeCycles / tot : 0.0, (unsigned long long)st.nativeCycles,
                (unsigned long long)st.interpretedInstructions);
        rt.WriteMismatchReport(stderr);
    }
    return 0;
}
